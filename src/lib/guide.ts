export const guideFor = (path: string): GuidePage | null => GUIDE[path] ?? (path.startsWith('/event/') ? GUIDE['/calendar'] : null)

// מה כבר נוסה: נשמר בדפדפן הזה בלבד
const LS_TRIED = 'sc_tried_v1'
const LS_SEEN = 'sc_guide_seen_v1'
const read = (k: string): string[] => { try { return JSON.parse(localStorage.getItem(k) ?? '[]') as string[] } catch { return [] } }
const add = (k: string, v: string) => { try { localStorage.setItem(k, JSON.stringify([...new Set([...read(k), v])])) } catch { /* אחסון חסום */ } }

export const tried = () => new Set(read(LS_TRIED))
export const markTried = (key: string) => add(LS_TRIED, key)
export const seenGuide = (path: string) => read(LS_SEEN).includes(path)
export const markSeenGuide = (path: string) => add(LS_SEEN, path)
export const itemKey = (path: string, i: GuideItem) => `${path}|${i.t}`
// סך הכול: כמה אפשרויות יש באפליקציה, וכמה מהן נוסו
export const potential = () => {
  const done = tried()
  const all = Object.entries(GUIDE).flatMap(([p, g]) => g.items.filter((i) => i.to || i.ask || i.act).map((i) => itemKey(p, i)))
  return { total: all.length, done: all.filter((k) => done.has(k)).length }
}
